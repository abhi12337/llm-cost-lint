"""Generate a demo project with wasteful LLM calls to try llm-cost-lint on.

    python examples/make_demo.py demo-llm-app
    llm-cost-lint scan demo-llm-app

The demo has a FastAPI backend (api/) and an Express + Vercel AI SDK server (web/). Each has
one file with the mistakes this tool looks for (copied from tests/fixtures/*_vulnerable) and
one file doing the same work correctly (copied from tests/fixtures/*_clean), which must NOT be
reported. Nothing in it is ever run and it contains no keys.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIXTURES = HERE.parent / "tests" / "fixtures"

FILES = {
    "api/app.py": FIXTURES / "py_vulnerable" / "app.py",
    "api/app_fixed.py": FIXTURES / "py_clean" / "app.py",
    "web/src/server.ts": FIXTURES / "ts_vulnerable" / "src" / "server.ts",
    "web/src/server_fixed.ts": FIXTURES / "ts_clean" / "src" / "server.ts",
}

README = """# demo-llm-app

Generated by llm-cost-lint's examples/make_demo.py. `api/app.py` and `web/src/server.ts`
contain LLM calls that waste money or break in production; the `*_fixed` files do the same
work correctly and produce no findings.
"""


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    out = Path(argv[1])
    if out.exists() and any(out.iterdir()):
        print(f"error: {out} exists and is not empty", file=sys.stderr)
        return 2
    for rel, src in FILES.items():
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    (out / "README.md").write_text(README, encoding="utf-8")
    print(f"Demo project written to {out}. Now run:  llm-cost-lint scan {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
